"""
summarize_run.py — regenerate output/RESULTS.md from output/run_facts.json

Author : Anna

The pipeline records every figure it produces into run_facts.json while it
runs; this script turns that record into the human-readable summary. Because
the summary is generated from the record — never typed by hand — the numbers
in RESULTS.md always belong to the most recent execution, whoever ran it.

  python summarize_run.py
"""

from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
FACTS = os.path.join(ROOT, "output", "run_facts.json")
TARGET = os.path.join(ROOT, "output", "RESULTS.md")


def money(v: float) -> str:
    return f"${v:,.0f}"


def main() -> None:
    with open(FACTS, encoding="utf-8") as fh:
        f = json.load(fh)
    a, e = f["aggregate"], f["eda"]
    c1, c2 = f["cleaning_phase1"], f["cleaning_phase2"]
    ft, o = f["features"], f["outliers"]
    kind = a.get("data_kind", "unknown")
    sample = kind.startswith("sample")

    lines = [
        "# Run Results — Independent Reproduction",
        "",
        f"**Author: {f.get('_author', 'Anna')}** · generated by "
        "`summarize_run.py` from `run_facts.json`",
        "",
    ]
    if sample:
        lines += [
            "> ⚠️ **Data used in this run: synthetic sample data** "
            "(`make_sample_data.py`, CRMLS schema, seeded RNG). The mortgage "
            "series is real (FRED MORTGAGE30US, fetched live). Every number "
            "below was produced by this execution. Replace the raw files "
            "with real CRMLS exports and re-run for production numbers.",
            "",
        ]
    else:
        lines += [
            "> Data used in this run: real CRMLS monthly exports "
            "(see `data_kind` in `run_facts.json`).",
            "",
        ]
    lines += [
        "## What the run produced",
        "",
        "| Stage | Result (this run) |",
        "|---|---|",
        f"| 1 Aggregate | Sold {a['sold_rows']:,} Residential rows · "
        f"Listed {a['listed_rows']:,} |",
        f"| 2 EDA | Sold median ClosePrice {money(e['sold_median_close_price'])} · "
        f"mean {money(e['sold_mean_close_price'])} · median DaysOnMarket "
        f"{e['sold_median_days_on_market']:.0f} · FRED rates merged |",
        f"| 3 Cleaning I | Sparse columns dropped: Sold "
        f"{len(c1['sold_dropped_columns'])}, Listed "
        f"{len(c1['listed_dropped_columns'])} · any-invalid: Sold "
        f"{c1['sold_any_invalid']:,}, Listed {c1['listed_any_invalid']:,} · "
        f"geo null {c1['sold_geo_null_pct']}% / {c1['listed_geo_null_pct']}% |",
        f"| 4 Cleaning II | Coordinates outside California: Sold "
        f"{c2['sold_outside_ca']:,}, Listed {c2['listed_outside_ca']:,} · "
        f"records with ≥1 flag: {c2['sold_any_flag_records']:,} / "
        f"{c2['listed_any_flag_records']:,} |",
        f"| 5 Features | ppsf valid {ft['ppsf_valid_pct']}% · price_ratio "
        f"valid {ft['price_ratio_valid_pct']}% · {ft['counties']} counties · "
        f"monthly trend {ft['months_in_trend']} months |",
        f"| 6 Outliers | Excluded {o['rows_excluded']:,} of "
        f"{o['rows_before']:,} → **analysis-ready {o['rows_analysis_ready']:,} "
        f"rows** · median ClosePrice {money(o['median_close_before'])} → "
        f"{money(o['median_close_after'])} |",
        "",
        "## Output files (all from this run)",
        "- `sold_analysis_ready.csv` — final analysis dataset",
        "- `segment_by_county.csv` / `segment_by_subtype.csv` / "
        "`segment_by_office.csv`",
        "- `monthly_market_trend.csv`, `mortgage_monthly_avg.csv`",
        "- `sold_distribution.csv`, `sold_missing_profile.csv`, "
        "`listed_missing_profile.csv`",
        "- `run_facts.json` — machine-readable copy of every figure above",
        "",
    ]
    with open(TARGET, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(TARGET, ROOT)} from run_facts.json "
          f"(data: {kind})")


if __name__ == "__main__":
    main()
